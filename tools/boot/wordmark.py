# The boot screen's "Microsoft(TM) Longhorn" wordmark as SVG paths, fitted letter by letter to the
# Longhorn 4015-4029 kernel boot bitmap (ntoskrnl BITMAP 1, 640x480; assets-src/longhorn-boot).
# The original is a 16-colour bitmap of a Segoe-family face; the glyphs here are Selawik
# (Microsoft's open Segoe UI fallback, OFL, assets-src/longhorn-boot/fonts/selawik), each scaled
# to the bitmap's cap height and centred on the bitmap letter's ink box, so the spacing is the
# original's. Output: path data in the bitmap's 640x480 pixel space, for index.html.
#
# usage: python3 -I tools/boot/wordmark.py <selawik dir> > src/scenes/session/bootWordmark.js
import json, re, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

d = sys.argv[1]
# letter ink boxes measured in the bitmap (x0, x1 inclusive), baseline, cap height in px
LONGHORN = dict(font='selawk.ttf', text='Longhorn', cap=22.4, base=319.4,
                boxes=[None, (None, 321), (324, 336), (339, 354), (356, 368), (371, 385), (388, 395), (398, 410)], first=293)
MICROSOFT = dict(font='selawksb.ttf', text='Microsoft', cap=9.8, base=292.9,
                 boxes=[(293, 303), (306, 307), (309, 315), (317, 320), (322, 328), None, None, None, (None, 354)], first=None, group=(330, 354))

def word(spec):
    f = TTFont(f"{d}/{spec['font']}")
    gs = f.getGlyphSet(); cmap = f.getBestCmap()
    capH = f['OS/2'].sCapHeight
    k = spec['cap'] / capH
    names = [cmap[ord(c)] for c in spec['text']]
    def bounds(n):
        bp = BoundsPen(gs); gs[n].draw(bp); return bp.bounds
    ink = [bounds(n) for n in names]
    widths = [(b[2] - b[0]) * k for b in ink]
    # target ink left x per letter
    xs = [None] * len(names)
    for i, b in enumerate(spec['boxes']):
        if b and b[0] is not None: xs[i] = (b[0] + b[1] + 1) / 2 - widths[i] / 2
    if spec['text'] == 'Longhorn':
        xs[0] = spec['first']                               # L starts the word
        xs[1] = 321 + 1 - widths[1]                         # o ends at the merged box's right
    else:
        # "soft" is one merged ink box: spread it with the font's own advances
        g0, g1 = spec['group']
        adv = [gs[n].width * k for n in names[5:9]]
        lsb = [ink[5 + j][0] * k for j in range(4)]
        span = sum(adv[:3]) + lsb[3] + widths[8] - lsb[0]
        s = (g1 + 1 - g0) / span
        x = g0 - lsb[0] * s
        for j in range(4):
            xs[5 + j] = x + lsb[j] * s
            x += adv[j] * s
    out = []
    for n, b, x in zip(names, ink, xs):
        pen = SVGPathPen(gs)
        # font units -> px: scale k, flip y, ink left at x, baseline at base
        t = TransformPen(pen, (k, 0, 0, -k, x - b[0] * k, spec['base']))
        gs[n].draw(t)
        out.append(pen.getCommands())
    return ' '.join(out)

def tm():
    # the tiny superscript TM after "Microsoft": 6x3 px at (359, 285) in the bitmap
    f = TTFont(f"{d}/selawksb.ttf"); gs = f.getGlyphSet(); cmap = f.getBestCmap()
    n = cmap[0x2122]
    bp = BoundsPen(gs); gs[n].draw(bp); b = bp.bounds
    k = 3.4 / (b[3] - b[1])
    pen = SVGPathPen(gs)
    gs[n].draw(TransformPen(pen, (k * 6.4 / ((b[2] - b[0]) * k), 0, 0, -k, 359 - b[0] * k * 6.4 / ((b[2] - b[0]) * k), 285 + b[3] * k)))
    return pen.getCommands()

r2 = lambda p: re.sub(r'-?\d+\.\d+', lambda m: ('%.2f' % float(m.group(0))).rstrip('0').rstrip('.'), p)
paths = {'longhorn': r2(word(LONGHORN)), 'microsoft': r2(word(MICROSOFT)), 'tm': r2(tm())}
print('// Generated by tools/boot/wordmark.py: the boot screen\'s "Microsoft(TM) Longhorn" in the kernel')
print('// bitmap\'s 640x480 pixel space (Selawik glyphs fitted to the Longhorn 4015-4029 boot bitmap).')
for k, v in paths.items(): print(f'export const {k.upper()} = {json.dumps(v)}')

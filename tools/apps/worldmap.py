#!/usr/bin/env python3
"""Write src/apps/applet/worldMap.js, the Time Zone tab's world map, from Natural Earth's 1:110m
land polygons (public domain; assets-src/natural-earth/ne_110m_land.geojson, see
assets-src/SOURCES.md section 11).

usage: python3 -I tools/apps/worldmap.py [geojson] [out.js]

Projection: Miller cylindrical (the look of the XP map's flat world), in map units where one
degree of longitude is 1 (x 0..360 from 180 W). Latitudes 78 N to 58 S are kept (Antarctica
and the far north are cut, as on the XP map). Rings are simplified with Douglas-Peucker
(TOL map units), islands smaller than MIN_AREA are dropped, and coordinates are written with
one decimal, so the path stays small.
"""
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'assets-src', 'natural-earth', 'ne_110m_land.geojson')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'src', 'apps', 'applet', 'worldMap.js')
TOL = 0.45
MIN_AREA = 2.0
LAT_N, LAT_S = 78.0, -58.0


def miller(lat):
    p = math.radians(max(-89.9, min(89.9, lat)))
    return math.degrees(1.25 * math.log(math.tan(math.pi / 4 + 0.4 * p)))


Y_N, Y_S = miller(LAT_N), miller(LAT_S)


def project(lon, lat):
    return (lon + 180.0, Y_N - miller(lat))  # y 0 at LAT_N, down


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]
        bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        n = math.hypot(dx, dy) or 1e-9
        best, bi = -1.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * (px - ax) - dx * (py - ay)) / n if n > 1e-9 else math.hypot(px - ax, py - ay)
            if d > best:
                best, bi = d, i
        if best > tol and bi > 0:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]


def area(pts):
    s = 0.0
    for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
        s += x0 * y1 - x1 * y0
    return abs(s) / 2


def rings(geom):
    if geom['type'] == 'Polygon':
        yield from geom['coordinates']
    elif geom['type'] == 'MultiPolygon':
        for poly in geom['coordinates']:
            yield from poly


def main():
    with open(SRC) as f:
        data = json.load(f)
    parts = []
    npts = 0
    for feat in data['features']:
        for ring in rings(feat['geometry']):
            if max(lat for _, lat in ring) < LAT_S:
                continue  # Antarctica
            pts = [project(lon, lat) for lon, lat in ring]
            if pts[0] == pts[-1]:
                pts = pts[:-1]
            if area(pts) < MIN_AREA:
                continue
            # split the ring at two far points so DP keeps a closed outline
            k = max(range(len(pts)), key=lambda i: (pts[i][0] - pts[0][0]) ** 2 + (pts[i][1] - pts[0][1]) ** 2)
            s = dp(pts[: k + 1], TOL)[:-1] + dp(pts[k:] + [pts[0]], TOL)[:-1]
            if len(s) < 3:
                continue
            npts += len(s)
            out = []
            px = py = None
            for i, (x, y) in enumerate(s):
                xi, yi = round(x * 10), round(y * 10)
                if i == 0:
                    out.append(f'M{xi / 10:g} {yi / 10:g}')
                else:
                    # relative steps: shorter than absolute coordinates
                    out.append(f'l{(xi - px) / 10:g} {(yi - py) / 10:g}')
                px, py = xi, yi
            parts.append(''.join(out) + 'z')
    d = ''.join(parts).replace(' -', '-')
    h = round(Y_S * -1 + Y_N, 2)
    js = (
        '// Generated by tools/apps/worldmap.py from Natural Earth 1:110m land (public domain,\n'
        '// assets-src/SOURCES.md section 11): Miller cylindrical, 78 N to 58 S, simplified.\n'
        '// Map units: 1 = one degree of longitude, x 0..360 from 180 W, y 0 at 78 N, down.\n'
        f'export const MAP_W = 360\nexport const MAP_H = {h}\n'
        f'// the y of a latitude (for placing things on the map)\n'
        f'export const mapY = (lat) => {Y_N:.4f} - (180 / Math.PI) * 1.25 * Math.log(Math.tan(Math.PI / 4 + (0.4 * lat * Math.PI) / 180))\n'
        f"export const LAND = '{d}'\n"
    )
    with open(OUT, 'w') as f:
        f.write(js)
    print(f'{len(parts)} rings, {npts} points, path {len(d)} bytes, height {h}')


main()
